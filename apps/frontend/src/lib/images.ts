function bySlug(slug: string): string | undefined {
  const normalized = slug.toLowerCase()
  if (normalized.includes('bayam')) return IMG.bayam
  if (normalized.includes('kangkung')) return IMG.bayam
  if (normalized.includes('wortel')) return IMG.wortel
  if (normalized.includes('brokoli')) return IMG.brokoli
  if (normalized.includes('tomat') || normalized.includes('cherry')) return IMG.tomat
  if (normalized.includes('jagung')) return IMG.jagung
  return undefined
}

function byRecipeSlug(slug: string): string | undefined {
  const normalized = slug.toLowerCase()
  if (normalized.includes('bayam')) return IMG['pecel-bayam']
  if (normalized.includes('asem')) return IMG['sayur-asem']
  if (normalized.includes('brokoli')) return IMG['tumis-brokoli']
  if (normalized.includes('sop') || normalized.includes('bening')) return IMG['sayur-sop']
  if (normalized.includes('salad')) return IMG.salad
  return undefined
}

export const productImage = (product: { slug?: string; name?: string }): string =>
  bySlug(product.slug ?? product.name ?? '') ?? IMG.bayam

export const recipeImage = (recipe: { slug?: string; title?: string }): string =>
  byRecipeSlug(recipe.slug ?? recipe.title ?? '') ?? IMG['tumis-brokoli']

